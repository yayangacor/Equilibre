// Writes src/landing/faceMeshData.ts: MediaPipe's canonical face mesh (468 vertices, 898 triangles), read from the
// geometry metadata inside public/models/face_landmarker.task. The landing visuals draw this mesh as their face, so
// the wireframe has the same topology MediaPipe fits to a real face. Run: node scripts/face-mesh-data.ts
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { inflateRawSync } from "node:zlib";

const TASK = fileURLToPath(new URL("../public/models/face_landmarker.task", import.meta.url));
const OUT = fileURLToPath(new URL("../src/landing/faceMeshData.ts", import.meta.url));
const ENTRY = "geometry_pipeline_metadata_landmarks.binarypb";

/** One file out of a zip archive (the .task bundle is a plain zip). */
function unzipEntry(zip: Buffer, name: string): Buffer {
  const eocd = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (eocd < 0) throw new Error("not a zip file");
  let at = zip.readUInt32LE(eocd + 16);
  for (let k = zip.readUInt16LE(eocd + 10); k > 0; k--) {
    const method = zip.readUInt16LE(at + 10);
    const size = zip.readUInt32LE(at + 20);
    const nameLen = zip.readUInt16LE(at + 28);
    const skip = nameLen + zip.readUInt16LE(at + 30) + zip.readUInt16LE(at + 32);
    const local = zip.readUInt32LE(at + 42);
    if (zip.toString("utf8", at + 46, at + 46 + nameLen) === name) {
      const start = local + 30 + zip.readUInt16LE(local + 26) + zip.readUInt16LE(local + 28);
      const data = zip.subarray(start, start + size);
      if (method === 0) return data;
      if (method === 8) return inflateRawSync(data);
      throw new Error(`zip method ${method}`);
    }
    at += 46 + skip;
  }
  throw new Error(`${name} not found`);
}

type Field = { num: number; wire: number; value: number | Buffer };

/** Top-level fields of a protobuf message (varint, 32/64-bit and length-delimited only). */
function fields(buf: Buffer): Field[] {
  const out: Field[] = [];
  let i = 0;
  const varint = () => {
    let shift = 0;
    let v = 0;
    for (;;) {
      const c = buf[i++];
      v += (c & 0x7f) * 2 ** shift;
      if (c < 0x80) return v;
      shift += 7;
    }
  };
  while (i < buf.length) {
    const key = varint();
    const num = Math.floor(key / 8);
    const wire = key & 7;
    if (wire === 0) out.push({ num, wire, value: varint() });
    else if (wire === 1) out.push({ num, wire, value: buf.subarray(i, (i += 8)) });
    else if (wire === 2) {
      const n = varint();
      out.push({ num, wire, value: buf.subarray(i, (i += n)) });
    } else if (wire === 5) out.push({ num, wire, value: buf.subarray(i, (i += 4)) });
    else throw new Error(`wire type ${wire}`);
  }
  return out;
}

/** A packed repeated varint field. */
function packedVarints(buf: Buffer): number[] {
  const out: number[] = [];
  let i = 0;
  while (i < buf.length) {
    let shift = 0;
    let v = 0;
    for (;;) {
      const c = buf[i++];
      v += (c & 0x7f) * 2 ** shift;
      if (c < 0x80) break;
      shift += 7;
    }
    out.push(v);
  }
  return out;
}

// GeometryPipelineMetadata { Mesh3d canonical_mesh = 1; ... }
// Mesh3d { vertex_type = 1 (VERTEX_PT: x, y, z, u, v); primitive_type = 2 (TRIANGLE); float vertex_buffer = 3;
//          uint32 index_buffer = 4 }
const meta = unzipEntry(readFileSync(TASK), ENTRY);
const mesh = fields(meta).find((f) => f.num === 1 && f.wire === 2)?.value;
if (!(mesh instanceof Buffer)) throw new Error("canonical_mesh missing");
const vertexBuffer: number[] = [];
const indexBuffer: number[] = [];
for (const f of fields(mesh)) {
  if (f.num === 3 && f.value instanceof Buffer) {
    for (let k = 0; k < f.value.length; k += 4) vertexBuffer.push(f.value.readFloatLE(k));
  } else if (f.num === 4) {
    if (f.value instanceof Buffer && f.wire === 2) indexBuffer.push(...packedVarints(f.value));
    else if (typeof f.value === "number") indexBuffer.push(f.value);
  }
}
if (vertexBuffer.length !== 468 * 5 || indexBuffer.length !== 898 * 3) {
  throw new Error(`unexpected mesh: ${vertexBuffer.length / 5} vertices, ${indexBuffer.length / 3} triangles`);
}

const vertices: number[] = [];
for (let k = 0; k < vertexBuffer.length; k += 5) vertices.push(...vertexBuffer.slice(k, k + 3).map((v) => Math.round(v * 1000) / 1000));

/** Numbers as a wrapped array literal body. */
function wrap(values: number[], width = 116): string {
  const lines: string[] = [];
  let line = "";
  for (const v of values) {
    const item = `${Object.is(v, -0) ? 0 : v},`;
    if (line.length + item.length + 1 > width) {
      lines.push(line);
      line = "";
    }
    line += line ? ` ${item}` : item;
  }
  if (line) lines.push(line);
  return lines.map((l) => `  ${l}`).join("\n");
}

writeFileSync(
  OUT,
  `// Generated by scripts/face-mesh-data.ts from public/models/face_landmarker.task (${ENTRY}). Do not edit.
// MediaPipe's canonical face mesh, Copyright 2020 The MediaPipe Authors, Apache License 2.0.
// Vertex i is face landmark i: x, y, z in centimetres, x to the image right, y up, z towards the camera.

export const CANONICAL_VERTICES: readonly number[] = [
${wrap(vertices)}
];

/** Triangles as vertex index triples. */
export const CANONICAL_TRIANGLES: readonly number[] = [
${wrap(indexBuffer)}
];
`,
);
console.log(`${OUT}: ${vertices.length / 3} vertices, ${indexBuffer.length / 3} triangles`);
